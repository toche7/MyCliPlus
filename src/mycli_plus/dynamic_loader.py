import importlib.util
import sys
from pathlib import Path
from typing import Any, Callable

ToolEntry = tuple[str, dict[str, Any], Callable[..., Any]]


def _load_module(path: Path, module_name: str) -> Any:
    spec = importlib.util.spec_from_file_location(module_name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Cannot load tool module: {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    try:
        spec.loader.exec_module(module)
    except BaseException:
        sys.modules.pop(module_name, None)
        raise
    return module


def _module_entries(module: Any, filename: str) -> list[ToolEntry]:
    entries: list[ToolEntry] = []

    bundled_tools = getattr(module, "SYSTEM_TOOLS", {})
    if not isinstance(bundled_tools, dict):
        raise ValueError(f"Invalid SYSTEM_TOOLS mapping in {filename}.")
    for name, entry in bundled_tools.items():
        try:
            schema, function = entry
        except (TypeError, ValueError) as error:
            raise ValueError(f"Invalid tool entry '{name}' in {filename}.") from error
        entries.append((name, schema, function))

    schema = getattr(module, "SCHEMA", None)
    if schema is not None:
        try:
            function_name = schema["function"]["name"]
            function = getattr(module, function_name)
        except (KeyError, TypeError, AttributeError) as error:
            raise ValueError(f"Invalid tool definition in {filename}.") from error
        entries.append((function_name, schema, function))

    return entries


def _register(
    entries: list[ToolEntry],
    schemas: list[dict[str, Any]],
    functions: dict[str, Callable[..., Any]],
) -> None:
    names = [name for name, _, _ in entries]
    for index, name in enumerate(names):
        if name in functions or name in names[:index]:
            raise ValueError(f"Duplicate tool name: {name}")
    for name, schema, function in entries:
        schemas.append(schema)
        functions[name] = function


def load_dynamic_tools(
    tools_dir: Path | None = None,
    *,
    self_improve: bool = True,
    generated_dir: Path | None = None,
    warnings: list[str] | None = None,
    enabled_tools: tuple[str, ...] | None = None,
) -> tuple[list[dict[str, Any]], dict[str, Callable[..., Any]]]:
    """Load bundled tool modules and, optionally, tools the agent generated.

    Bundled modules that set SELF_IMPROVE_ONLY are skipped unless
    ``self_improve`` is true. ``enabled_tools`` filters the bundled tools only;
    tools generated by the agent are always loaded in self-improve mode.
    Modules in ``generated_dir`` are loaded best-effort: a broken one is
    skipped and reported through ``warnings``.
    """
    directory = tools_dir or Path(__file__).parent / "tools"
    schemas: list[dict[str, Any]] = []
    functions: dict[str, Callable[..., Any]] = {}

    for path in sorted(directory.glob("*.py")):
        if path.name == "__init__.py":
            continue

        module = _load_module(path, f"mycli_plus.tools.{path.stem}")
        if getattr(module, "SELF_IMPROVE_ONLY", False) and not self_improve:
            continue
        _register(_module_entries(module, path.name), schemas, functions)

    if enabled_tools is not None:
        unknown_tools = set(enabled_tools) - functions.keys()
        if unknown_tools:
            names = ", ".join(sorted(unknown_tools))
            raise ValueError(f"Unknown tool(s) in MYCLI_TOOLS: {names}.")
        selected = set(enabled_tools)
        schemas = [s for s in schemas if s["function"]["name"] in selected]
        functions = {n: f for n, f in functions.items() if n in selected}

    if self_improve and generated_dir is not None and generated_dir.is_dir():
        for path in sorted(generated_dir.glob("*.py")):
            try:
                module = _load_module(path, f"mycli_plus.generated_tools.{path.stem}")
                entries = _module_entries(module, path.name)
                if not entries:
                    raise ValueError("no SCHEMA found; keep the SCHEMA from the draft")
                _register(entries, schemas, functions)
            except Exception as error:
                if warnings is not None:
                    warnings.append(
                        f"Skipped generated tool {path.name}: "
                        f"{type(error).__name__}: {error}"
                    )

    return schemas, functions
